function failure(code, message, details = {}) {
  return { ok: false, code, message, ...details };
}

function ensureTrailingLf(text) {
  return text.endsWith('\n') ? text : `${text}\n`;
}

function normalizeTargets(targets) {
  if (targets === undefined || targets === null) return [...RUNTIME_HOST_TARGETS];
  const wanted = new Set(targets);
  return RUNTIME_HOST_TARGETS.filter((target) => wanted.has(target));
}

/** Render engine-owned text for a host: placeholders and `<runner>`. */
export function renderHostText(text, { version = '' } = {}) {
  return String(text)
    .replaceAll('<runner>', ROOT_COMMAND)
    .replaceAll('${RUNNER_CMD_DQ}', ROOT_COMMAND)
    .replaceAll('${RUNNER_CMD}', ROOT_COMMAND)
    .replaceAll('$RUNNER_CMD', ROOT_COMMAND)
    .replaceAll('${PROJECT_ROOT}', '.')
    .replaceAll('${PAYLOAD_HOME}', '.r2c')
    .replaceAll('${VERSION}', version);
}

function splitFrontmatter(text) {
  if (!text.startsWith('---\n')) return { fields: {}, body: text };
  const end = text.indexOf('\n---\n', 4);
  if (end === -1) return { fields: {}, body: text };
  const fields = {};
  for (const line of text.slice(4, end).split('\n')) {
    const match = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (match !== null) fields[match[1]] = match[2].replace(/^"(.*)"$/, '$1');
  }
  return { fields, body: text.slice(end + 5) };
}

function wrapSkill(stem, text) {
  const { fields, body } = splitFrontmatter(text);
  const description = fields.description ?? `r2c ${stem.slice(4)}`;
  return ensureTrailingLf(`---\nname: ${JSON.stringify(stem)}\ndescription: ${JSON.stringify(description)}\n---\n\n${body.replace(/^\n+/, '')}`);
}

function commandFiles(sourceRoot, targets, version) {
  const dir = join(sourceRoot, 'runtime/r2c/assets/commands');
  let names = [];
  try {
    names = readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && /^r2c-.*\.md$/.test(entry.name))
      .map((entry) => entry.name)
      .sort(compareCodePoints);
  } catch {
    names = [];
  }
  const files = [];
  for (const target of targets) {
    const layout = COMMAND_TARGETS[target];
    if (layout === undefined) continue;
    for (const name of names) {
      const stem = name.slice(0, -3);
      const text = renderHostText(readFileSync(join(dir, name), 'utf8'), { version });
      if (layout.style === 'skill') {
        files.push({ path: `${layout.root}/${stem}/SKILL.md`, kind: 'command', targets: [target], mode: 0o644, content: wrapSkill(stem, text) });
      } else {
        files.push({ path: `${layout.root}/${stem}.md`, kind: 'command', targets: [target], mode: 0o644, content: ensureTrailingLf(text) });
      }
    }
  }
  return files;
}

function listDirFiles(root, rel, filter) {
  const out = [];
  const walk = (current, prefix) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const absolute = join(current, entry.name);
      const relPath = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
      if (entry.isDirectory()) walk(absolute, relPath);
      else if (entry.isFile() && (filter === undefined || filter.test(entry.name))) out.push({ path: relPath, absolute });
    }
  };
  if (existsSync(root)) walk(root, rel);
  return out.sort((left, right) => compareCodePoints(left.path, right.path));
}

function hostFiles(sourceRoot, target, version) {
  const files = [];
  const merged = [];
  for (const rule of HOST_LAYOUT[target] ?? []) {
    if (rule.from !== undefined) {
      const absolute = join(sourceRoot, ...rule.from.split('/'));
      if (!existsSync(absolute)) continue;
      const text = renderHostText(readFileSync(absolute, 'utf8'), { version });
      if (rule.merge !== undefined) {
        merged.push({ path: rule.merge.path, pointer: rule.merge.pointer, text });
      } else {
        files.push({
          path: rule.to,
          kind: rule.kind ?? 'other',
          targets: [target],
          mode: rule.executable === true ? 0o755 : 0o644,
          content: ensureTrailingLf(text),
        });
      }
      continue;
    }
    if (rule.dir !== undefined) {
      const absolute = join(sourceRoot, ...rule.dir.split('/'));
      for (const entry of listDirFiles(absolute, '', rule.filter)) {
        files.push({
          path: `${rule.to}/${entry.path}`,
          kind: rule.kind ?? 'other',
          targets: [target],
          mode: rule.executable === true ? 0o755 : 0o644,
          content: ensureTrailingLf(renderHostText(readFileSync(entry.absolute, 'utf8'), { version })),
        });
      }
    }
  }
  return { files, merged };
}

function pointerGet(document, pointer) {
  let current = document;
  for (const part of pointer.split('.')) {
    if (current === null || typeof current !== 'object') return undefined;
    current = current[part];
  }
  return current;
}

function pointerSet(document, pointer, value) {
  const parts = pointer.split('.');
  let current = document;
  for (const part of parts.slice(0, -1)) {
    if (current[part] === null || typeof current[part] !== 'object') current[part] = {};
    current = current[part];
  }
  current[parts[parts.length - 1]] = value;
}

/** Accumulate pointer-level merges; returns planned JSON files and records. */
function mergeHostPointers(projectRoot, merges) {
  const documents = new Map();
  const records = [];
  for (const merge of merges) {
    if (!isInstallPath(merge.path)) throw Object.assign(new Error(`invalid merge path ${merge.path}`), { code: 'RUNTIME_PATH_INVALID' });
    const absolute = projectPath(projectRoot, merge.path);
    if (absolute === null) throw Object.assign(new Error(`merge path escapes project: ${merge.path}`), { code: 'RUNTIME_PATH_INVALID' });
    let document = documents.get(merge.path);
    if (document === undefined) {
      if (existsSync(absolute)) {
        try {
          document = JSON.parse(readFileSync(absolute, 'utf8'));
        } catch {
          throw Object.assign(new Error(`${merge.path} is not valid JSON`), { code: 'RUNTIME_MERGE_INVALID' });
        }
      } else {
        document = {};
      }
      documents.set(merge.path, document);
    }
    const source = JSON.parse(merge.text);
    const pointer = merge.pointer;
    const value = pointerGet(source, pointer) ?? source;
    pointerSet(document, pointer, value);
    records.push({ path: merge.path, pointer, value_sha256: sha256Hex(canonicalJson(value)) });
  }
  const files = [...documents.entries()].map(([path, document]) => ({
    path,
    kind: 'merge',
    targets: [],
    mode: 0o644,
    content: canonicalJson(document),
  }));
  return {
    files: files.sort((left, right) => comparePaths(left.path, right.path)),
    records: records.sort((left, right) => comparePaths(left.path, right.path) || compareCodePoints(left.pointer, right.pointer)),
  };
}

function collectRuntimeFiles(sourceRoot, targets, version) {
  const files = commandFiles(sourceRoot, targets, version);
  const merges = [];
  for (const target of targets) {
    const host = hostFiles(sourceRoot, target, version);
    files.push(...host.files);
    merges.push(...host.merged);
  }
  files.push({
    path: '.r2c/shims/hook.mjs',
    kind: 'hook',
    targets: sorted(targets),
    mode: 0o644,
    content: readFileSync(join(sourceRoot, 'runtime/r2c/assets/shims/hook.mjs'), 'utf8'),
  });
  files.push({
    path: LAUNCHER_PATH,
    kind: 'launcher',
    targets: sorted(targets),
    mode: 0o755,
    content: LAUNCHER_TEXT,
  });
  return { files, merges };
}

function engineVersionOf(sourceRoot) {
  try {
    const value = JSON.parse(readFileSync(join(sourceRoot, 'package.json'), 'utf8'));
    return typeof value.version === 'string' ? value.version : null;
  } catch {
    return null;
  }
}

function engineHomeRecord(projectRoot, engineHome) {
  if (engineHome === undefined || engineHome === null || engineHome === '') {
    return { home: ENGINE_ROOT, absoluteHome: projectPath(projectRoot, ENGINE_ROOT) };
  }
  const absoluteHome = resolve(engineHome);
  if (isInsideProject(projectRoot, absoluteHome)) {
    const rel = toPosix(absoluteHome.slice(resolve(projectRoot).length).replace(/^[/\\]+/, ''));
    return { home: rel === '' ? '.' : rel, absoluteHome };
  }
  return { home: toPosix(absoluteHome), absoluteHome };
}

function copyEngineTree(sourceRoot, destinationRoot) {
  const files = [];
  const walk = (current, target) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const absolute = join(current, entry.name);
      const next = join(target, entry.name);
      const info = lstatSync(absolute);
      if (info.isSymbolicLink()) {
        throw Object.assign(new Error(`engine source contains a symbolic link: ${entry.name}`), { code: 'ENGINE_SOURCE_SYMLINK' });
      }
      if (info.isDirectory()) {
        mkdirSync(next, { recursive: true });
        walk(absolute, next);
        continue;
      }
      if (!info.isFile()) continue;
      mkdirSync(dirname(next), { recursive: true });
      copyFileSync(absolute, next);
      const executable = (statSync(absolute).mode & 0o111) !== 0
        || /(?:^|[/\\])bin[/\\].*\.(?:js|mjs|cjs)$/.test(toPosix(absolute));
      if (executable) {
        try {
          chmodSync(next, 0o755);
        } catch {
          // Windows has no executable bit.
        }
      }
      files.push(next);
    }
  };
  walk(sourceRoot, destinationRoot);
  return files.sort(compareCodePoints);
}

function engineTreeMatches(sourceRoot, destinationRoot) {
  if (!existsSync(destinationRoot)) return false;
  try {
    let matches = true;
    const walk = (current, target) => {
      for (const entry of readdirSync(current, { withFileTypes: true })) {
        const absolute = join(current, entry.name);
        const next = join(target, entry.name);
        if (entry.isDirectory()) {
          walk(absolute, next);
          continue;
        }
        if (!existsSync(next)) return (matches = false);
        if (sha256File(absolute) !== sha256File(next)) return (matches = false);
      }
    };
    walk(sourceRoot, destinationRoot);
    return matches;
  } catch {
    return false;
  }
}

function computeCreatedDirs(projectRoot, paths) {
  const created = new Set();
  for (const path of paths) {
    for (const dir of ancestorDirs(path)) {
      const absolute = projectPath(projectRoot, dir);
      if (absolute === null) continue;
      if (lstatOrNull(absolute) === null) created.add(dir);
    }
  }
  return [...created].sort(comparePaths);
}

export function isRuntimeReceipt(value) {
  return value !== null && typeof value === 'object' && value.schema === RUNTIME_SCHEMA;
}

/** Parsed runtime receipt or `null`; unreadable/invalid receipts throw. */
export function readRuntimeReceipt(projectRoot) {
  const absolute = projectPath(projectRoot, RUNTIME_RECEIPT_PATH);
  if (absolute === null || !existsSync(absolute)) return null;
  const value = JSON.parse(readFileSync(absolute, 'utf8'));
  if (!isRuntimeReceipt(value)) {
    const error = new Error(`unsupported runtime receipt schema at ${RUNTIME_RECEIPT_PATH}`);
    error.code = 'RUNTIME_SCHEMA_UNSUPPORTED';
    throw error;
  }
  return value;
}

export function buildRuntimeReceipt({
  engine,
  hostTargets,
  files,
  merged,
  backups,
  installedAt,
  updatedAt,
}) {
  return {
    schema: RUNTIME_SCHEMA,
    engine: { version: engine.version, home: engine.home, entry: engine.entry },
    launcher: LAUNCHER_PATH,
    host_targets: sorted(hostTargets),
    files: [...files]
      .sort((left, right) => comparePaths(left.path, right.path))
      .map((file) => ({
        path: file.path,
        kind: file.kind,
        targets: sorted(file.targets ?? []),
        sha256: file.sha256,
        mode: file.mode === 0o755 || file.mode === '0755' ? '0755' : '0644',
      })),
    merged: [...merged].sort((left, right) => comparePaths(left.path, right.path) || compareCodePoints(left.pointer, right.pointer)),
    backups: [...backups].sort((left, right) => comparePaths(left.path, right.path)),
    installed_at: installedAt,
    updated_at: updatedAt,
  };
}

export function serializeRuntimeReceipt(receipt) {
  return canonicalJson(receipt);
}

/**
 * Install or upgrade the r2c runtime.
 *
 * Input: `{projectRoot, engineSource, engineVersion?, engineHome?, hostTargets?,
 * force?, dryRun?, clock?}`. Engine source is the extracted engine tree:
 * `bin/r2c.js` is the entry; `commands/r2c-*.md` and `hosts/<target>/**` are
 * the runtime-owned host assets.
 */
export function installRuntime(input = {}) {
  const clock = input.clock ?? (() => new Date());
  const dryRun = input.dryRun === true;
  const force = input.force === true;
  const projectRoot = resolve(input.projectRoot ?? process.cwd());

  if (!existsSync(projectRoot) || !statSync(projectRoot).isDirectory()) {
    return failure('PROJECT_NOT_FOUND', `project root is not a directory: ${projectRoot}`);
  }
  const engineSource = input.engineSource === undefined ? null : resolve(input.engineSource);
  if (engineSource === null || !existsSync(engineSource) || !statSync(engineSource).isDirectory()) {
    return failure('ENGINE_SOURCE_NOT_FOUND', 'the engine source directory is required');
  }
  const version = input.engineVersion ?? engineVersionOf(engineSource);
  if (typeof version !== 'string' || parseSemver(version) === null) {
    return failure('ENGINE_VERSION_INVALID', 'engineVersion must be a version string');
  }
  if (!existsSync(join(engineSource, 'bin', 'r2c.js'))) {
    return failure('ENGINE_ENTRY_MISSING', `engine source has no bin/r2c.js: ${toPosix(engineSource)}`);
  }
  if (!isInstallPath(ENGINE_ROOT)) return failure('RUNTIME_PATH_INVALID', 'invalid engine root');

  const targets = normalizeTargets(input.hostTargets);
  const home = engineHomeRecord(projectRoot, input.engineHome);
  const versionDir = join(home.absoluteHome, version);
  const entryRelative = `${home.home === '.' ? '' : `${home.home}/`}${version}/bin/r2c.js`;
  const entry = home.home === '.' ? `${version}/bin/r2c.js` : entryRelative;
  const entryIsAbsolute = /^[A-Za-z]:\//.test(entry) || entry.startsWith('/');
  const engine = {
    version,
    home: home.home,
    entry,
  };

  const assetRoot = input.assetRoot === undefined || input.assetRoot === null
    ? FRAMEWORK_ROOT
    : resolve(input.assetRoot);
  const { files: planned, merges } = collectRuntimeFiles(assetRoot, targets, version);
  let mergedPlan;
  try {
    mergedPlan = mergeHostPointers(projectRoot, merges);
  } catch (error) {
    return failure(error?.code ?? 'RUNTIME_MERGE_INVALID', error?.message ?? 'host pointer merge failed');
  }
  const allPlanned = [...planned, ...mergedPlan.files];

  const invalidPaths = allPlanned.filter((file) => !isInstallPath(file.path) || projectPath(projectRoot, file.path) === null);
  if (invalidPaths.length > 0) {
    return failure('RUNTIME_PATH_INVALID', `invalid runtime path: ${invalidPaths[0].path}`);
  }

  let previous;
  try {
    previous = readRuntimeReceipt(projectRoot);
  } catch (error) {
    return failure(error.code ?? 'RUNTIME_RECEIPT_INVALID', error.message);
  }
  const previousFiles = new Map((previous?.files ?? []).map((file) => [file.path, file]));
  const engineMatches = engineTreeMatches(engineSource, versionDir);
  const resolvedEngineEntry = entryIsAbsolute ? entry : join(projectRoot, ...entry.split('/'));

  const fileContents = allPlanned.map((file) => ({
    ...file,
    content: typeof file.content === 'string' ? file.content : '',
    sha256: sha256Hex(file.content),
  }));

  const conflicts = [];
  const writes = [];
  for (const file of fileContents) {
    const absolute = projectPath(projectRoot, file.path);
    const info = lstatOrNull(absolute);
    if (info === null) {
      writes.push({ op: 'create', file });
      continue;
    }
    if (info.isSymbolicLink() || !info.isFile()) {
      conflicts.push({ code: 'SYMLINK_AT_TARGET', path: file.path, message: `${file.path} is not a regular file` });
      continue;
    }
    if (sha256File(absolute) === file.sha256) continue;
    // Pointer-level merges are additive: an existing user config is never a
    // conflict, but it is backed up like any replaced runtime-owned file.
    if (file.kind === 'merge') {
      writes.push({ op: 'replace', file });
      continue;
    }
    const owned = previousFiles.has(file.path);
    if (!owned && !force) {
      conflicts.push({ code: 'RUNTIME_FILE_CONFLICT', path: file.path, message: `${file.path} exists and is not owned by the runtime receipt` });
      continue;
    }
    writes.push({ op: 'replace', file });
  }
  if (conflicts.length > 0) {
    return { ok: false, code: 'RUNTIME_CONFLICTS', message: `${conflicts.length} runtime path conflict(s); nothing was written`, conflicts };
  }
  const changed = !engineMatches || writes.length > 0 || previous === null || previous.engine.version !== version;
  if (!changed) {
    return {
      ok: true,
      code: 'OK',
      action: 'unchanged',
      runtime: previous,
      runtimePath: RUNTIME_RECEIPT_PATH,
      engine,
      files: previous.files.length,
      merged: previous.merged,
      wrote: [],
      pruned: [],
    };
  }
  if (dryRun) {
    return {
      ok: true,
      code: 'OK',
      action: 'would-install',
      dryRun: true,
      engine,
      files: fileContents.length,
      writes: writes.map((write) => write.file.path),
      merged: mergedPlan.records,
    };
  }

  let lock;
  try {
    lock = acquireProjectLock(projectRoot);
  } catch (error) {
    if (error?.code === 'LOCK_CONFLICT') return failure('LOCK_CONFLICT', error.message, { lock: error.message });
    throw error;
  }

  const stamp = String(clock().toISOString()).replace(/[:.]/g, '-');
  const engineCreated = !existsSync(versionDir);
  try {
    const writePaths = writes.map((write) => write.file.path);
    const createdDirs = computeCreatedDirs(projectRoot, [...writePaths, RUNTIME_RECEIPT_PATH]);
    const receiptExisted = lstatOrNull(projectPath(projectRoot, RUNTIME_RECEIPT_PATH)) !== null;
    const operations = writes.map((write) => ({ op: write.op, path: write.file.path, backup: write.op === 'replace' }));
    operations.push({ op: receiptExisted ? 'replace' : 'create', path: RUNTIME_RECEIPT_PATH, backup: false });
    const journal = prepareJournal({
      projectRoot,
      command: 'runtime',
      operations,
      createdDirs,
      projectionId: 'runtime',
      bundleId: version,
      stamp,
      clock,
    });

    try {
      writeJournal(projectRoot, journal);
      for (const dir of createdDirs) ensureProjectDirs(projectRoot, dir);
      if (!engineMatches) {
        if (existsSync(versionDir)) rmSync(versionDir, { recursive: true, force: true });
        mkdirSync(versionDir, { recursive: true });
        copyEngineTree(engineSource, versionDir);
      }
      if (!existsSync(resolvedEngineEntry)) {
        throw Object.assign(new Error('installed engine entry is missing'), { code: 'ENGINE_ENTRY_MISSING' });
      }
      for (const write of writes) {
        const absolute = projectPath(projectRoot, write.file.path);
        const dirs = ancestorDirs(write.file.path);
        if (dirs.length > 0) ensureProjectDirs(projectRoot, dirs[dirs.length - 1]);
        writeFileAtomic(absolute, write.file.content, write.file.mode);
        if (sha256File(absolute) !== write.file.sha256) {
          throw Object.assign(new Error(`post-write hash verification failed for ${write.file.path}`), { code: 'HASH_MISMATCH' });
        }
      }

      const now = clock().toISOString();
      const backups = journal.operations
        .filter((operation) => operation.backup !== null && operation.path !== RUNTIME_RECEIPT_PATH)
        .map((operation) => ({ path: operation.path, backup: operation.backup, sha256: operation.before_sha256 ?? null }));
      const runtimeFiles = writes
        .map((write) => write.file)
        .filter((file) => file.kind !== 'merge')
        .map((file) => ({
          path: file.path,
          kind: file.kind,
          targets: file.targets,
          sha256: sha256File(projectPath(projectRoot, file.path)),
          mode: file.mode,
        }));
      const unchangedFiles = fileContents.filter((file) => !writes.some((write) => write.file.path === file.path));
      for (const file of unchangedFiles) {
        if (file.kind === 'merge') continue;
        runtimeFiles.push({
          path: file.path,
          kind: file.kind,
          targets: file.targets,
          sha256: file.sha256,
          mode: file.mode,
        });
      }
      const receipt = buildRuntimeReceipt({
        engine,
        hostTargets: targets,
        files: runtimeFiles,
        merged: mergedPlan.records,
        backups,
        installedAt: previous?.installed_at ?? now,
        updatedAt: now,
      });
      const receiptAbsolute = projectPath(projectRoot, RUNTIME_RECEIPT_PATH);
      writeAbsoluteAtomic(receiptAbsolute, serializeRuntimeReceipt(receipt));

      const pruned = [];
      if (input.engineHome === undefined || input.engineHome === null || input.engineHome === '') {
        const engineRoot = projectPath(projectRoot, ENGINE_ROOT);
        for (const entryName of existsSync(engineRoot) ? readdirSync(engineRoot) : []) {
          if (entryName === version) continue;
          const candidate = join(engineRoot, entryName);
          if (!lstatOrNull(candidate)?.isDirectory()) continue;
          rmSync(candidate, { recursive: true, force: true });
          pruned.push(`${ENGINE_ROOT}/${entryName}`);
        }
      }

      journal.state = 'committed';
      journal.receipts_written = [RUNTIME_RECEIPT_PATH];
      writeJournal(projectRoot, journal);
      removeJournal(projectRoot);
      return {
        ok: true,
        code: 'OK',
        action: 'installed',
        runtime: receipt,
        runtimePath: RUNTIME_RECEIPT_PATH,
        engine,
        files: receipt.files.length,
        merged: receipt.merged,
        wrote: writePaths,
        backups,
        pruned,
      };
    } catch (error) {
      const outcome = rollbackJournal(projectRoot, journal);
      if (engineCreated) rmSync(versionDir, { recursive: true, force: true });
      if (outcome.failures.length > 0) {
        writeJournal(projectRoot, { ...journal, state: 'rollback-failed' });
        return failure('ROLLBACK_FAILED', 'runtime install failed and the rollback could not restore every path', {
          failures: outcome.failures,
          journal: '.r2c/install/pending.json',
          cause: error?.message ?? String(error),
        });
      }
      removeJournal(projectRoot);
      return failure(error?.code === 'ENGINE_ENTRY_MISSING' ? 'ENGINE_ENTRY_MISSING' : 'RUNTIME_INSTALL_FAILED', error?.message ?? 'runtime install failed', {
        cause: error?.code ?? 'IO',
      });
    }
  } finally {
    releaseProjectLock(projectRoot, lock);
  }
}
